// Visuels de repli : un mot inconnu reçoit toujours le même (choisi d'après
// ses lettres), et deux mots inconnus différents en ont souvent des différents.
export const IMAGES_REPLI: readonly string[] = ['⭐', '🌟', '💡', '🎈', '🔷', '🍀', '🎯', '🧩', '🌈', '🎨', '🙂', '😊', '🔶', '💫', '🪁', '🔆']

// Petits mots ignorés quand on cherche l'image d'une expression.
const MOTS_VIDES = new Set(['le', 'la', 'les', 'l', 'un', 'une', 'des', 'de', 'du', 'd', 'a', 'au', 'aux', 'et', 'en', 'sur', 'sous', 'pour', 'avec'])

function cle(mot: string): string {
  return normaliserReponse(mot)
    .replace(/[’`]/g, "'")
    .replace(/[.!?,;:«»"]/g, '')
    .trim()
}

const DICTIONNAIRE: Map<string, string> = (() => {
  const m = new Map<string, string>()
  for (const [emoji, mots] of GROUPES_IMAGES) {
    for (const mot of mots.split('|')) {
      const k = cle(mot)
      if (k !== '' && !m.has(k)) m.set(k, emoji)
    }
  }
  return m
})()

// Formes possibles d'un mot au singulier (« chevaux » → « cheval »…).
function singuliers(k: string): string[] {
  const formes: string[] = []
  if (k.endsWith('eaux')) formes.push(k.slice(0, -1))
  if (k.endsWith('aux')) formes.push(k.slice(0, -3) + 'al')
  if (k.endsWith('s') || k.endsWith('x')) formes.push(k.slice(0, -1))
  return formes
}

function chercher(k: string): string | null {
  for (const f of [k, ...singuliers(k)]) {
    const e = DICTIONNAIRE.get(f)
    if (e) return e
  }
  return null
}

// Image trouvée dans le dictionnaire pour ce mot, ou null s'il est inconnu.
// Une expression (« salle de bain ») prend l'image de l'expression entière,
// sinon celle de son premier mot connu.
export function imageConnue(mot: string): string | null {
  const k = cle(mot)
  if (k === '') return null
  const directe = chercher(k)
  if (directe) return directe
  const morceaux = k
    .split(/[\s'’-]+/)
    .filter((m) => m !== '' && !MOTS_VIDES.has(m))
  if (morceaux.length < 2) return null
  for (const m of morceaux) {
    const e = chercher(m)
    if (e) return e
  }
  return null
}

// Image d'un mot : toujours un visuel, même pour un mot inconnu.
export function imageDuMot(mot: string): string {
  const connue = imageConnue(mot)
  if (connue) return connue
  const k = cle(mot)
  let h = 0
  for (const c of k) h = (h * 31 + (c.codePointAt(0) ?? 0)) >>> 0
  return IMAGES_REPLI[h % IMAGES_REPLI.length]
}
